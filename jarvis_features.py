# ============================================================

def create_powerpoint(topic, content=None):

    topic = topic.strip()

    if not content:
        content = f"""
Introduction

{topic} is an important subject that can be studied through
its concepts, applications and practical examples.

Key Concepts

Understanding the fundamental concepts of {topic} is the first
step toward learning the subject.

Applications

{topic} can have practical applications depending on the
specific field and problem being studied.

Advantages

Understanding {topic} can improve technical knowledge and
problem-solving ability.

Challenges

There can be practical, technical and security challenges
associated with {topic}.

Best Practices

Following appropriate methods and learning from practical
examples can improve understanding.

Conclusion

{topic} can be explored further through practical exercises,
research and experimentation.
"""

    filename = safe_filename(topic) + ".pptx"

    filepath = os.path.join(PPT_DIR, filename)

    presentation = Presentation()

    # Title slide
    slide = presentation.slides.add_slide(
        presentation.slide_layouts[0]
    )

    slide.shapes.title.text = topic

    slide.placeholders[1].text = (
        "Generated by JARVIS"
    )

    # Content slides
    paragraphs = [
        p.strip()
        for p in content.split("\n")
        if p.strip()
    ]

    current_title = None
    current_text = []

    for paragraph in paragraphs:

        # Treat short lines as headings
        if len(paragraph) < 45:

            if current_title:

                slide = presentation.slides.add_slide(
                    presentation.slide_layouts[1]
                )

                slide.shapes.title.text = current_title

                slide.placeholders[1].text = (
                    "\n".join(current_text)
                )

            current_title = paragraph
            current_text = []

        else:

            current_text.append(paragraph)

    # Add final slide
    if current_title:

        slide = presentation.slides.add_slide(
            presentation.slide_layouts[1]
        )

        slide.shapes.title.text = current_title

        slide.placeholders[1].text = (
            "\n".join(current_text)
        )

    presentation.save(filepath)

    return filepath


