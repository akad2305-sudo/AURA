def create_pdf(topic, content=None):

    topic = topic.strip()

    if not content:
        content = f"""
This document was created by JARVIS.

Topic:
{topic}

Introduction

This document provides an overview of {topic}.

Key Concepts

The topic can be studied by understanding its basic concepts,
important terminology, practical applications, advantages,
limitations, and security considerations.

Conclusion

Understanding {topic} provides a useful foundation for further
study and practical work.
"""

    filename = safe_filename(topic) + ".pdf"

    filepath = os.path.join(PDF_DIR, filename)

    document = SimpleDocTemplate(
        filepath,
        pagesize=A4
    )

    styles = getSampleStyleSheet()

    story = []

    story.append(
        Paragraph(topic, styles["Title"])
    )

    story.append(
        Spacer(1, 20)
    )

    for paragraph in content.split("\n"):

        paragraph = paragraph.strip()

        if paragraph:

            story.append(
                Paragraph(
                    paragraph,
                    styles["BodyText"]
                )
            )

            story.append(
                Spacer(1, 8)
            )

    document.build(story)

    return filepath


