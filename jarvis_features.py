def create_all_documents(topic, content=None):

    pdf = create_pdf(topic, content)

    word = create_word(topic, content)

    ppt = create_powerpoint(topic, content)

    return {
        "pdf": pdf,
        "word": word,
        "ppt": ppt
    }


