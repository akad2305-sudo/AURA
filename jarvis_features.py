def create_word(topic, content=None):

    topic = topic.strip()

    if not content:
        content = f"""
Introduction

This document was created by JARVIS.

The topic of this document is {topic}.

Key Concepts

The subject can be understood by studying its important concepts,
terminology, applications, advantages, limitations and practical
examples.

Conclusion

Further study and practical experimentation can provide a deeper
understanding of {topic}.
"""

    filename = safe_filename(topic) + ".docx"

    filepath = os.path.join(WORD_DIR, filename)

    document = Document()

    document.add_heading(topic, 0)

    document.add_paragraph(
        "Generated by JARVIS"
    )

    for paragraph in content.split("\n"):

        paragraph = paragraph.strip()

        if paragraph:

            document.add_paragraph(paragraph)

    document.save(filepath)

    return filepath


